import express from "express";
import authenticate from "../modules/config/authenticate";
import multer from "multer";
import { generateError } from "../config/Error/functions";
import { downloadOnboardingDocument, employeeOnboardingHistory, getEmployeeOnboarding, listEmployeeOnboarding, mutateEmployeeOnboarding, onboardingEmployees, onboardingOwners, onboardingPublishedTemplates, onboardingWorkspace, getAssignedOnboardingPolicy, listOnboardingPolicyAcknowledgements } from "../services/onboarding/employeeOnboarding.service";
import { getTemplate, listTemplates, mutateTemplate, templateAssetCategories, templateHistory, templateOptions, templatePeople } from "../services/onboarding/onboardingTemplate.service";
import { getOnboardingAutomationSettings, listOnboardingAutomationAudit, listOnboardingAutomationJobs, retryOnboardingAutomation, runOnboardingAutomation, saveOnboardingAutomationSettings } from "../services/onboarding/onboardingAutomation.service";
import { checkOnboardingDocumentScanner, getOnboardingDocumentSecurity, listUploadSecurityEvents } from "../services/onboarding/onboardingDocumentSecurity.service";
import { getRetentionPolicy, getRetentionRequest, listRetentionAudit, listRetentionDocuments, listRetentionRequests, mutateRetention } from "../services/onboarding/onboardingRetention.service";
import { getOnboardingPolicy, getPublishedOnboardingPolicy, listOnboardingPolicies, mutateOnboardingPolicy, onboardingPolicyHistory, onboardingPolicyOptions } from "../services/onboarding/onboardingPolicy.service";
import { getOnboardingAssets, mutateOnboardingAsset, onboardingAssetHistory, onboardingAssetOptions } from "../services/onboarding/onboardingAsset.service";

const router = express.Router();
router.use(authenticate);
router.use((_req, res, next) => { res.setHeader("Cache-Control", "private, no-store"); next(); });
router.get("/workspace", onboardingWorkspace);
router.get("/policy-options", onboardingPolicyOptions);
router.get("/policies", listOnboardingPolicies);
router.post("/policies", mutateOnboardingPolicy("created"));
router.get("/policies/:policyId", getOnboardingPolicy);
router.put("/policies/:policyId", mutateOnboardingPolicy("updated"));
router.post("/policies/:policyId/publish", mutateOnboardingPolicy("published"));
router.post("/policies/:policyId/discard-draft", mutateOnboardingPolicy("discarded"));
router.post("/policies/:policyId/archive", mutateOnboardingPolicy("archived"));
router.post("/policies/:policyId/restore", mutateOnboardingPolicy("restored"));
router.get("/policies/:policyId/versions", onboardingPolicyHistory("versions"));
router.get("/policies/:policyId/versions/:versionId", getPublishedOnboardingPolicy);
router.get("/policies/:policyId/audit", onboardingPolicyHistory("audit"));
router.get("/document-security", getOnboardingDocumentSecurity);
router.post("/document-security/check-scanner", checkOnboardingDocumentScanner);
router.get("/document-security/events", listUploadSecurityEvents);
router.get("/retention/policy", getRetentionPolicy);
router.put("/retention/policy", mutateRetention("policy"));
router.get("/retention/documents", listRetentionDocuments);
router.post("/retention/documents/:documentId/start-clock", mutateRetention("clock"));
router.put("/retention/documents/:documentId/hold", mutateRetention("hold"));
router.get("/retention/requests", listRetentionRequests);
router.post("/retention/requests", mutateRetention("create"));
router.get("/retention/requests/:requestId", getRetentionRequest);
router.post("/retention/requests/:requestId/decision", mutateRetention("decision"));
router.post("/retention/requests/:requestId/withdraw", mutateRetention("withdraw"));
router.post("/retention/requests/:requestId/retry", mutateRetention("retry"));
router.get("/retention/audit", listRetentionAudit);
router.get("/automation/settings", getOnboardingAutomationSettings);
router.put("/automation/settings", saveOnboardingAutomationSettings);
router.get("/automation/audit", listOnboardingAutomationAudit);
router.get("/automation/jobs", listOnboardingAutomationJobs);
router.post("/automation/jobs", runOnboardingAutomation);
router.post("/automation/jobs/:jobId/retry", retryOnboardingAutomation);
router.get("/employees", onboardingEmployees);
router.get("/owners", onboardingOwners);
router.get("/assignment-templates", onboardingPublishedTemplates);
router.get("/instances", listEmployeeOnboarding);
router.post("/instances", mutateEmployeeOnboarding("assign"));
router.get("/instances/:instanceId", getEmployeeOnboarding);
router.get("/instances/:instanceId/audit", employeeOnboardingHistory);
router.post("/instances/:instanceId/actions", mutateEmployeeOnboarding("instance"));
router.post("/instances/:instanceId/tasks/:taskId/actions", mutateEmployeeOnboarding("task"));
router.get("/instances/:instanceId/tasks/:taskId/policy", getAssignedOnboardingPolicy);
router.get("/instances/:instanceId/tasks/:taskId/acknowledgements", listOnboardingPolicyAcknowledgements);
router.get("/instances/:instanceId/tasks/:taskId/assets", getOnboardingAssets);
router.post("/instances/:instanceId/tasks/:taskId/assets", mutateOnboardingAsset("link"));
router.post("/instances/:instanceId/tasks/:taskId/assets/:linkId/detach", mutateOnboardingAsset("detach"));
router.get("/instances/:instanceId/tasks/:taskId/asset-options", onboardingAssetOptions);
router.get("/instances/:instanceId/tasks/:taskId/asset-events", onboardingAssetHistory);
const upload = multer({ storage: multer.memoryStorage(), limits: { fileSize: 5 * 1024 * 1024, files: 1, fields: 5, fieldSize: 2000 } }).single("file");
router.post("/instances/:instanceId/tasks/:taskId/documents", (req, res, next) => upload(req, res, (error: any) => error ? next(generateError(error.code === "LIMIT_FILE_SIZE" ? "Document must be 5 MB or smaller" : "Invalid document upload", error.code === "LIMIT_FILE_SIZE" ? 413 : 422)) : next()), mutateEmployeeOnboarding("upload"));
router.get("/instances/:instanceId/tasks/:taskId/documents/:documentId", downloadOnboardingDocument);
router.get("/options", templateOptions);
router.get("/people", templatePeople);
router.get("/asset-categories", templateAssetCategories);
router.get("/templates", listTemplates);
router.post("/templates", mutateTemplate("created"));
router.get("/templates/:templateId", getTemplate);
router.put("/templates/:templateId", mutateTemplate("updated"));
router.post("/templates/:templateId/publish", mutateTemplate("published"));
router.post("/templates/:templateId/discard-draft", mutateTemplate("discarded"));
router.post("/templates/:templateId/archive", mutateTemplate("archived"));
router.post("/templates/:templateId/restore", mutateTemplate("restored"));
router.get("/templates/:templateId/versions", templateHistory("versions"));
router.get("/templates/:templateId/audit", templateHistory("audit"));
export default router;
