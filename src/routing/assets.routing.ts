import express from "express";
import multer from "multer";
import authenticate from "../modules/config/authenticate";
import { assetEmployees, assetHistory, assetLocations, assetWorkspace, getAsset, getAssetAssignment, listAssetAssignments, listAssets, mutateAsset } from "../services/assets/asset.service";
import { assetIncidentHistory, getAssetIncident, listAssetIncidents, mutateAssetIncident } from "../services/assets/assetIncident.service";
import { assetServiceHistory, getAssetServiceOrder, listAssetServiceOrders, mutateAssetServiceOrder } from "../services/assets/assetService.service";
import { getAssetWriteOff, listAssetWriteOffs, mutateAssetWriteOff, writeOffHistory } from "../services/assets/assetWriteOff.service";
import { clearanceCustody, clearanceEmployees, clearanceHistory, clearanceReviews, getAssetClearance, listAssetClearances, mutateAssetClearance } from "../services/assets/assetClearance.service";
import { assetImportHistory, assetImportTemplate, exportAssetInventory, getAssetImport, listAssetImports, mutateAssetImport, previewAssetImport } from "../services/assets/assetTransfer.service";
import { assetContext } from "../services/assets/asset.utils";
import { ASSET_FILE_LIMIT, canImportAssets } from "../services/assets/assetTransfer.utils";
import { generateError } from "../config/Error/functions";
import { assetCategoryHistory, getAssetCategory, listAssetCategories, mutateAssetCategory } from "../services/assets/assetCategory.service";
import { assetDocumentHistory, assetDocumentUploadAccess, downloadAssetDocumentVersion, getAssetDocument, listAssetDocuments, mutateAssetDocument, uploadAssetDocument } from "../services/assets/assetDocument.service";
import { ASSET_DOCUMENT_LIMITS } from "../schemas/Assets/AssetDocument.schema";
import { downloadAssetLabels, lookupAssetLabel } from "../services/assets/assetLabel.service";
import { assetExportHistory, changeAssetExport, createAssetExport, downloadAssetExport, getAssetExport, listAssetExports } from "../services/assets/assetExport.service";
import { assetPurchaseHistory, checkAssetWarrantyReminders, getAssetPurchase, listAssetPurchases, saveAssetPurchase } from "../services/assets/assetPurchase.service";
import { assetDisposalHistory, getAssetDisposal, listAssetDisposals, mutateAssetDisposal } from "../services/assets/assetDisposal.service";

const router = express.Router();
router.use(authenticate);
router.use((_req, res, next) => { res.setHeader("Cache-Control", "private, no-store"); next(); });
router.get("/categories", listAssetCategories);
router.post("/categories", mutateAssetCategory("created"));
router.get("/categories/:categoryId", getAssetCategory);
router.put("/categories/:categoryId", mutateAssetCategory("updated"));
router.post("/categories/:categoryId/archive", mutateAssetCategory("archived"));
router.post("/categories/:categoryId/restore", mutateAssetCategory("restored"));
router.get("/categories/:categoryId/events", assetCategoryHistory);
const importFile = multer({ storage: multer.memoryStorage(), limits: { fileSize: ASSET_FILE_LIMIT, files: 1, fields: 2, parts: 3, fieldSize: 1024 }, fileFilter: (_req, file, callback) => { callback(file.originalname.toLowerCase().endsWith(".csv") ? null : generateError("Asset import accepts CSV files only", 422), true); } }).single("file");
router.get("/imports/template", assetImportTemplate);
router.get("/imports", listAssetImports);
router.post("/imports/preview", (req, _res, next) => { try { if (!canImportAssets(assetContext(req, "manage"))) throw generateError("Import Asset Inventory permission is required", 403); next(); } catch (error) { next(error); } }, (req, res, next) => { importFile(req, res, (error: any) => { if (!error) next(); else next(error instanceof multer.MulterError ? generateError(error.code === "LIMIT_FILE_SIZE" ? "Asset CSV must not exceed 1 MB" : "Upload one CSV file and its request id", error.code === "LIMIT_FILE_SIZE" ? 413 : 400) : error); }); }, previewAssetImport);
router.get("/imports/:importId", getAssetImport);
router.get("/imports/:importId/rows", assetImportHistory("rows"));
router.get("/imports/:importId/events", assetImportHistory("events"));
router.post("/imports/:importId/apply", mutateAssetImport("apply"));
router.post("/imports/:importId/cancel", mutateAssetImport("cancel"));
router.get("/workspace", assetWorkspace);
router.get("/purchases", listAssetPurchases);
router.post("/warranty-reminders/run", checkAssetWarrantyReminders);
router.get("/disposals", listAssetDisposals);
router.post("/disposals", mutateAssetDisposal("created"));
router.get("/disposals/:disposalId", getAssetDisposal);
router.get("/disposals/:disposalId/events", assetDisposalHistory);
router.post("/disposals/:disposalId/approve", mutateAssetDisposal("approve"));
router.post("/disposals/:disposalId/reject", mutateAssetDisposal("reject"));
router.post("/disposals/:disposalId/withdraw", mutateAssetDisposal("withdraw"));
router.post("/disposals/:disposalId/complete", mutateAssetDisposal("complete"));
router.get("/exports", listAssetExports);
router.post("/exports", createAssetExport);
router.get("/exports/:exportId", getAssetExport);
router.get("/exports/:exportId/events", assetExportHistory);
router.get("/exports/:exportId/download", downloadAssetExport);
router.post("/exports/:exportId/cancel", changeAssetExport("cancel"));
router.post("/exports/:exportId/retry", changeAssetExport("retry"));
router.get("/locations", assetLocations);
router.get("/employees", assetEmployees);
router.get("/clearances/employees", clearanceEmployees);
router.get("/clearances", listAssetClearances);
router.post("/clearances", mutateAssetClearance("created"));
router.get("/clearances/:clearanceId", getAssetClearance);
router.get("/clearances/:clearanceId/custody", clearanceCustody);
router.get("/clearances/:clearanceId/reviews", clearanceReviews);
router.get("/clearances/:clearanceId/events", clearanceHistory);
router.post("/clearances/:clearanceId/clear", mutateAssetClearance("clear"));
router.post("/clearances/:clearanceId/reopen", mutateAssetClearance("reopen"));
router.post("/clearances/:clearanceId/cancel", mutateAssetClearance("cancel"));
router.post("/clearances/:clearanceId/reschedule", mutateAssetClearance("reschedule"));
router.post("/clearances/:clearanceId/notes", mutateAssetClearance("note"));
router.get("/write-offs", listAssetWriteOffs);
router.post("/write-offs", mutateAssetWriteOff("created"));
router.get("/write-offs/:writeOffId", getAssetWriteOff);
router.get("/write-offs/:writeOffId/events", writeOffHistory("events"));
router.get("/write-offs/:writeOffId/ledger", writeOffHistory("ledger"));
router.post("/write-offs/:writeOffId/approve", mutateAssetWriteOff("approve"));
router.post("/write-offs/:writeOffId/reject", mutateAssetWriteOff("reject"));
router.post("/write-offs/:writeOffId/withdraw", mutateAssetWriteOff("withdraw"));
router.post("/write-offs/:writeOffId/recover", mutateAssetWriteOff("recover"));
router.post("/write-offs/:writeOffId/receipts", mutateAssetWriteOff("receipt"));
router.post("/write-offs/:writeOffId/receipts/:receiptId/reverse", mutateAssetWriteOff("reverse"));
router.get("/service-orders", listAssetServiceOrders);
router.post("/service-orders", mutateAssetServiceOrder("created"));
router.get("/service-orders/:serviceOrderId", getAssetServiceOrder);
router.get("/service-orders/:serviceOrderId/events", assetServiceHistory);
router.post("/service-orders/:serviceOrderId/start", mutateAssetServiceOrder("start"));
router.post("/service-orders/:serviceOrderId/work-complete", mutateAssetServiceOrder("work_complete"));
router.post("/service-orders/:serviceOrderId/receive-unrepaired", mutateAssetServiceOrder("receive_unrepaired"));
router.post("/service-orders/:serviceOrderId/inspection", mutateAssetServiceOrder("inspection"));
router.post("/service-orders/:serviceOrderId/cancel", mutateAssetServiceOrder("cancel"));
router.post("/service-orders/:serviceOrderId/notes", mutateAssetServiceOrder("note"));
router.get("/incidents", listAssetIncidents);
router.post("/incidents", mutateAssetIncident("reported"));
router.get("/incidents/:incidentId", getAssetIncident);
router.get("/incidents/:incidentId/events", assetIncidentHistory);
router.post("/incidents/:incidentId/review", mutateAssetIncident("review"));
router.post("/incidents/:incidentId/resolve", mutateAssetIncident("resolve"));
router.post("/incidents/:incidentId/dismiss", mutateAssetIncident("dismiss"));
router.get("/inventory", listAssets);
router.post("/inventory", mutateAsset("created"));
router.get("/inventory/export", exportAssetInventory);
router.post("/inventory/lookup", lookupAssetLabel);
router.post("/inventory/labels", downloadAssetLabels);
const documentUpload = multer({ storage: multer.memoryStorage(), limits: { fileSize: ASSET_DOCUMENT_LIMITS.bytes, files: 1, fields: 6, parts: 7, fieldSize: 2000 }, fileFilter: (_req, file, callback) => { callback(["application/pdf", "image/png", "image/jpeg", "image/jpg"].includes(file.mimetype.toLowerCase()) ? null : generateError("Choose a PDF, JPG or PNG asset file", 422), true); } }).single("file");
const documentFile = (req: any, res: any, next: any) => documentUpload(req, res, (error: any) => { if (!error) next(); else next(error instanceof multer.MulterError ? generateError(error.code === "LIMIT_FILE_SIZE" ? "Asset files must be 5 MB or smaller" : "Upload one asset file and its document details", error.code === "LIMIT_FILE_SIZE" ? 413 : 400) : error); });
router.get("/inventory/:assetId/documents", listAssetDocuments);
router.post("/inventory/:assetId/documents", assetDocumentUploadAccess, documentFile, uploadAssetDocument("uploaded"));
router.get("/inventory/:assetId/documents/:documentId", getAssetDocument);
router.put("/inventory/:assetId/documents/:documentId", mutateAssetDocument("updated"));
router.get("/inventory/:assetId/documents/:documentId/versions", assetDocumentHistory("versions"));
router.post("/inventory/:assetId/documents/:documentId/versions", assetDocumentUploadAccess, documentFile, uploadAssetDocument("replaced"));
router.get("/inventory/:assetId/documents/:documentId/versions/:versionNumber/download", downloadAssetDocumentVersion);
router.get("/inventory/:assetId/documents/:documentId/events", assetDocumentHistory("events"));
router.post("/inventory/:assetId/documents/:documentId/archive", mutateAssetDocument("archived"));
router.post("/inventory/:assetId/documents/:documentId/restore", mutateAssetDocument("restored"));
router.get("/inventory/:assetId", getAsset);
router.get("/inventory/:assetId/purchase", getAssetPurchase);
router.put("/inventory/:assetId/purchase", saveAssetPurchase);
router.get("/inventory/:assetId/purchase/events", assetPurchaseHistory);
router.put("/inventory/:assetId", mutateAsset("updated"));
router.post("/inventory/:assetId/issue", mutateAsset("issued"));
router.post("/inventory/:assetId/state", mutateAsset("state"));
router.get("/inventory/:assetId/assignments", assetHistory("assignments"));
router.get("/inventory/:assetId/audit", assetHistory("audit"));
router.get("/assignments", listAssetAssignments);
router.get("/assignments/:assignmentId", getAssetAssignment);
router.post("/assignments/:assignmentId/acknowledge", mutateAsset("acknowledged"));
router.post("/assignments/:assignmentId/request-return", mutateAsset("request_return"));
router.post("/assignments/:assignmentId/return", mutateAsset("returned"));
router.post("/assignments/:assignmentId/void", mutateAsset("voided"));
export default router;
