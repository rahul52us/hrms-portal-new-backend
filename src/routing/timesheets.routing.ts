import express from "express";
import { getTimesheetPayrollCycles, getTimesheetPayrollPreview, lockTimesheetPayroll, changeTimesheetPayrollLock } from "../services/timesheet/timesheetPayroll.service";
import { listTimesheetAutomation, runTimesheetAutomation, listTimesheetContextEvents } from "../services/timesheet/timesheetAutomation.service";
import { listTimesheetCorrections, openTimesheetCorrection, getTimesheetCorrectionPreview, settleTimesheetCorrection, getTimesheetPayrollDayHistory } from "../services/timesheet/timesheetCorrection.service";
import authenticate from "../modules/config/authenticate";
import { guardTimesheetWrite } from "../services/timesheet/timesheetWriteGuard";
import { getMyTimesheetDay, getMyTimesheetHistory, getMyTimesheetPlanner, getMyTimesheetSummary, listMyTimesheetProjects, listMyTimesheetWorkTypes, saveMyTimesheetDraft } from "../services/timesheet/timesheet.service";
import { actOnTimesheet, getTimesheetSubmission, listTimesheetSubmissions } from "../services/timesheet/timesheetSubmission.service";
import { exportTimesheetOperations, getTimesheetOperationsDay, getTimesheetOperationsLookup, getTimesheetOperationsOptions, getTimesheetOperationsReport } from "../services/timesheet/timesheetOperations.service";
import { changeTimesheetDayControls, getTimesheetDayControls } from "../services/timesheet/timesheetDayControl.service";
import { listTimesheetReassignmentOptions, reassignTimesheetApproval } from "../services/timesheet/timesheetReassignment.service";

const router = express.Router();
router.use(authenticate);
router.use((_req, res, next) => { res.setHeader("Cache-Control", "private, no-store"); next(); });
router.use(guardTimesheetWrite);
router.get("/automation", listTimesheetAutomation);
router.post("/automation", runTimesheetAutomation);
router.get("/payroll/cycles", getTimesheetPayrollCycles);
router.get("/payroll/corrections", listTimesheetCorrections);
router.get("/payroll/corrections/:correctionId", getTimesheetCorrectionPreview);
router.post("/payroll/corrections/:correctionId/settle", settleTimesheetCorrection);
router.get("/payroll/cycles/:period", getTimesheetPayrollPreview);
router.post("/payroll/cycles/:period/lock", lockTimesheetPayroll);
router.post("/payroll/inputs/:inputId/state", changeTimesheetPayrollLock);
router.post("/payroll/inputs/:inputId/corrections", openTimesheetCorrection);
router.get("/operations/employees/:employeeId/day/:date/context-events", listTimesheetContextEvents());
router.get("/operations/employees/:employeeId/day/:date/payroll-history", getTimesheetPayrollDayHistory());
router.get("/day/:date/context-events", listTimesheetContextEvents(true));
router.get("/day/:date/payroll-history", getTimesheetPayrollDayHistory(true));
router.get("/operations/options", getTimesheetOperationsOptions);
router.get("/operations/lookups", getTimesheetOperationsLookup);
router.get("/operations/register", getTimesheetOperationsReport("register"));
router.get("/operations/monthly", getTimesheetOperationsReport("monthly"));
router.get("/operations/effort", getTimesheetOperationsReport("effort"));
router.get("/operations/export", exportTimesheetOperations);
router.get("/operations/employees/:employeeId/day/:date", getTimesheetOperationsDay);
router.get("/operations/employees/:employeeId/day/:date/controls", getTimesheetDayControls());
router.post("/operations/employees/:employeeId/day/:date/controls", changeTimesheetDayControls);
router.get("/summary", getMyTimesheetSummary);
router.get("/planner", getMyTimesheetPlanner);
router.get("/submissions", listTimesheetSubmissions);
router.get("/submissions/:submissionId", getTimesheetSubmission);
router.get("/submissions/:submissionId/reassignment-options", listTimesheetReassignmentOptions);
router.post("/submissions/:submissionId/reassign", reassignTimesheetApproval);
for (const action of ["approve", "return", "reject", "withdraw", "reopen"] as const) router.post(`/submissions/:submissionId/${action}`, actOnTimesheet(action));
router.post("/day/:date/submit", actOnTimesheet("submit"));
router.get("/day/:date", getMyTimesheetDay);
router.put("/day/:date", saveMyTimesheetDraft);
router.get("/day/:date/projects", listMyTimesheetProjects);
router.get("/day/:date/work-types", listMyTimesheetWorkTypes);
router.get("/day/:date/history", getMyTimesheetHistory);
router.get("/day/:date/controls", getTimesheetDayControls(true));
export default router;
