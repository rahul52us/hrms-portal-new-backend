import assert from "node:assert/strict";
import mongoose from "mongoose";
import { AssetIncident, AssetIncidentEvent } from "../../schemas/Assets/AssetIncident.schema";
import { attachEffectivePermissions } from "../permissions/permission.utils";
import { assetDto, assignmentDto } from "./asset.utils";
import { canReadIncident, incidentDto, incidentOccurredAt } from "./assetIncident.utils";

const id = () => new mongoose.Types.ObjectId();
const company = id(), employee = id(), reporter = id(), incidentId = id(), assignment = id();
const actor = (role: string, _id = id(), permissions?: any) => ({ actor: attachEffectivePermissions({ user: { _id, role, company, permissions } }), company });
const manager = actor("hradmin"), recipient = actor("user", employee), unrelated = actor("user"), source = actor("user", reporter);
const incident = { _id: incidentId, company, asset: id(), assignment, employee, reportedBy: reporter, active: true, status: "open", revision: 1 };
const heldAsset = { _id: incident.asset, currentAssignment: assignment, status: "issued", openIncident: incidentId, condition: "good", revision: 2 };
assert.equal(canReadIncident(recipient, incident), true);
assert.equal(canReadIncident(source, incident), true);
assert.equal(canReadIncident(unrelated, incident), false);
assert.equal(canReadIncident(manager, incident), true);
assert.equal(incidentDto(manager, incident, heldAsset).canResolve, true);
assert.equal(incidentDto(actor("hradmin", employee), incident, heldAsset).canResolve, false, "Custodian cannot clear their own case");
assert.equal(incidentDto(actor("user", id(), { view_assets: true }), incident, heldAsset).canResolve, false);
assert.equal(incidentDto(manager, { ...incident, active: false }, heldAsset).canResolve, false);
assert.equal(incidentDto(manager, incident, { ...heldAsset, openIncident: null }).canResolve, false);
assert.equal(assetDto(manager, { ...heldAsset, status: "available", currentAssignment: null }).canIssue, false);
assert.equal(assetDto(manager, { ...heldAsset, status: "maintenance", currentAssignment: null }).canMakeAvailable, false);
assert.equal(assetDto(manager, { ...heldAsset, status: "available", currentAssignment: null }).canEdit, false);
const handover = { _id: assignment, employee, active: true, status: "issued", acknowledgedAt: null };
assert.equal(assignmentDto(manager, handover, heldAsset).canReturn, true, "Hold never blocks physical recovery");
assert.equal(assignmentDto(manager, handover, heldAsset).canVoid, false);
assert.equal(assignmentDto(recipient, handover, heldAsset).canReportIncident, false);
assert.equal(assignmentDto(recipient, handover, { ...heldAsset, openIncident: null }).canReportIncident, true);
assert.equal(assignmentDto(recipient, { ...handover, _id: id(), active: false }, heldAsset).openIncident, null, "Old holder must not learn a later holder's case");
const now = new Date("2026-11-14T12:00:00Z");
assert.equal(incidentOccurredAt("2026-11-14T10:30:00+05:30", now).toISOString(), "2026-11-14T05:00:00.000Z");
for (const invalid of [null, "2026-11-14", "2026-11-14T10:00", "2026-02-30T10:00:00Z", "2026-11-14T24:00:00Z", "2026-11-15T00:00:00Z"]) assert.throws(() => incidentOccurredAt(invalid, now));
assert.ok(AssetIncident.schema.indexes().some(([fields, options]: any) => fields.company && fields.asset && options.unique && options.partialFilterExpression?.active));
assert.ok(AssetIncidentEvent.schema.indexes().some(([fields, options]: any) => fields.company && fields.actor && fields.requestId && options.unique));
console.log("Asset incident assertions passed: timestamp validation, owned reads, independent review, holds, physical recovery and unique indexes.");
