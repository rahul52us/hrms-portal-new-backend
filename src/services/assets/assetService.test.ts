import assert from "node:assert/strict";
import mongoose from "mongoose";
import { AssetServiceOrder, AssetServiceEvent } from "../../schemas/Assets/AssetServiceOrder.schema";
import { attachEffectivePermissions } from "../permissions/permission.utils";
import { assetDto } from "./asset.utils";
import { serviceCost, serviceDto } from "./assetService.utils";
import { incidentDto } from "./assetIncident.utils";

const id = () => new mongoose.Types.ObjectId();
const company = id(), actor = attachEffectivePermissions({ user: { _id: id(), company, role: "hradmin" } }), ctx = { actor, company };
const order = { _id: id(), active: true, status: "open", providerType: "external", externalDispatched: false, cycle: 1 };
const asset = { _id: id(), openService: order._id, currentAssignment: null, status: "maintenance", revision: 4, condition: "good", maintenanceReleaseBlocked: true };
assert.equal(serviceDto(ctx, order, asset).canStart, true);
assert.equal(serviceDto(ctx, order, asset).canCancel, true);
assert.equal(serviceDto(ctx, order, asset).canInspect, false);
const dispatched = { ...order, status: "in_progress", externalDispatched: true };
assert.equal(serviceDto(ctx, dispatched, asset).canCompleteWork, true);
assert.equal(serviceDto(ctx, dispatched, asset).canReceiveUnrepaired, true);
assert.equal(serviceDto(ctx, dispatched, asset).canCancel, false);
assert.equal(serviceDto(ctx, { ...order, status: "awaiting_inspection" }, asset).canInspect, true);
assert.equal(serviceDto(ctx, { ...order, active: false, status: "completed" }, asset).canAddNote, false);
assert.equal(serviceDto(ctx, order, { ...asset, currentAssignment: id() }).canStart, false);
assert.equal(serviceDto(ctx, order, { ...asset, openService: id() }).canStart, false);
const viewer = { company, actor: attachEffectivePermissions({ user: { _id: id(), company, role: "user", permissions: { view_assets: true } } }) };
assert.equal(serviceDto(viewer, order, asset).canStart, false);
assert.equal(assetDto(ctx, asset).canEdit, false);
assert.equal(assetDto(ctx, asset).canMakeAvailable, false);
assert.equal(assetDto(ctx, { ...asset, openService: null, status: "available" }).canIssue, false);
assert.equal(assetDto(ctx, { ...asset, openService: null }).canOpenService, true);
assert.equal(assetDto(ctx, { ...asset, openService: null }).canRetire, true);
assert.equal(assetDto(ctx, { ...asset, openService: null, maintenanceReleaseBlocked: false }).canMakeAvailable, true);
const incident = { _id: id(), active: true, employee: id(), status: "open" };
const incidentCapabilities = incidentDto(ctx, incident, { ...asset, openIncident: incident._id });
assert.equal(incidentCapabilities.canResolve, false, "Inspection resolution cannot bypass active service");
assert.equal(incidentCapabilities.canReview, true);
assert.equal(incidentCapabilities.canDismiss, true, "Invalid-report dismissal does not release service clearance");
assert.deepEqual(serviceCost(null, "INR"), { actualCostMinor: null, currency: "INR" });
assert.deepEqual(serviceCost(0, "INR"), { actualCostMinor: 0, currency: "INR" });
assert.deepEqual(serviceCost(125000, "USD"), { actualCostMinor: 125000, currency: "USD" });
for (const value of [-1, 1.5, "100", NaN, Infinity, 1000000000001]) assert.throws(() => serviceCost(value, "INR"));
assert.throws(() => serviceCost(0, "BAD"));
assert.ok(AssetServiceOrder.schema.indexes().some(([fields, options]: any) => fields.company && fields.asset && options.unique && options.partialFilterExpression?.active));
assert.ok(AssetServiceEvent.schema.indexes().some(([fields, options]: any) => fields.company && fields.actor && fields.requestId && options.unique));
console.log("Asset service assertions passed: capabilities, provider custody, release/incident guards, minor-unit costs and indexes.");
