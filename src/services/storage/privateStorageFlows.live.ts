import assert from "node:assert/strict";
import mongoose from "mongoose";
import File from "../../schemas/Storage/PrivateStoredFile.schema";
import Document from "../../schemas/User/Document";
import Audit from "../../schemas/Storage/EmployeeDocumentAudit.schema";
import Attachment from "../../schemas/Leave/LeaveAttachment.schema";
import Leave from "../../schemas/Leave/LeaveRequest.schema";
import Correction from "../../schemas/Attendance/AttendanceRegularizationRequest.schema";
import User from "../../schemas/User/User";
import Approval from "../../schemas/Approval/ApprovalInstance.schema";
import { cleanupPrivateStoredFile } from "./privateStoredFile.service";

export async function testPrivateStorageFlows(input: { company: mongoose.Types.ObjectId; hradmin: mongoose.Types.ObjectId; admin: mongoose.Types.ObjectId; hr: mongoose.Types.ObjectId; employee: mongoose.Types.ObjectId; other: mongoose.Types.ObjectId; viewer: mongoose.Types.ObjectId; base: string; token: (who: mongoose.Types.ObjectId) => string }) {
  const { company, hradmin, admin, hr, employee, other, viewer, base, token } = input;
  await Promise.all([File.init(), Document.init(), Audit.init(), Attachment.init()]);
  let sequence = 0;
  const requestId = () => `private-storage-flow-${++sequence}`;
  const pdf = Buffer.from("%PDF-1.4\nPrivate HRMS storage fixture\n%%EOF");
  const data = `data:application/pdf;base64,${pdf.toString("base64")}`;
  const r2 = process.argv.includes("--r2");
  const call = async (who: mongoose.Types.ObjectId | null, route: string, method = "GET", body?: any, expected = 200) => {
    const response = await fetch(`${base}/api${route}`, { method, headers: { "Content-Type": "application/json", ...(who ? { Authorization: `Bearer ${token(who)}` } : {}) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    const result: any = await response.json();
    assert.equal(response.status, expected, `${method} ${route}: ${JSON.stringify(result)}`);
    return result;
  };
  const download = async (who: mongoose.Types.ObjectId | null, route: string, expected = 200) => {
    const response = await fetch(`${base}/api${route}`, { headers: who ? { Authorization: `Bearer ${token(who)}` } : {} });
    assert.equal(response.status, expected, `${route} download: ${await (response.status === expected ? Promise.resolve("") : response.text())}`);
    if (expected === 200) {
      assert.equal(response.headers.get("cache-control"), "private, no-store");
      assert.match(response.headers.get("content-disposition") || "", /^attachment;/);
      assert.equal(response.headers.get("x-content-type-options"), "nosniff");
      assert.equal(response.headers.get("location"), null);
      assert.deepEqual(Buffer.from(await response.arrayBuffer()), pdf);
    } else assert.equal(response.headers.get("content-disposition"), null);
  };
  const rules = async (value: any) => { assert.equal((await fetch(`${process.env.R2_TEST_ENDPOINT}/__control`, { method: "POST", body: JSON.stringify(value) })).status, 200); };
  const location = new mongoose.Types.ObjectId();
  await User.collection.updateOne({ _id: employee }, { $set: { department: "Engineering", team: "Python", officeLocation: location, reportingManager: viewer } });
  await User.collection.updateOne({ _id: hr }, { $set: { hrScope: { departments: ["Engineering"], teams: ["Python"], officeLocations: [location] } } });
  const attachmentBody = { name: "medical-proof.pdf", type: "application/pdf", size: pdf.length, data, requestId: requestId() };
  const uploads = await Promise.all([0, 1].map(() => call(employee, "/leave/attachments", "POST", attachmentBody, 201)));
  const attachment = uploads[0].data;
  assert.equal(uploads[1].data._id, attachment._id);
  assert.equal(await Attachment.countDocuments({ company, uploadRequestId: attachmentBody.requestId }), 1);
  assert.equal((await call(employee, "/leave/attachments", "POST", attachmentBody, 201)).replayed, true);
  await call(employee, "/leave/attachments", "POST", { ...attachmentBody, name: "different.pdf" }, 409);
  await call(employee, "/leave/attachments", "POST", { ...attachmentBody, requestId: undefined }, 422);
  await call(employee, "/leave/attachments", "POST", { ...attachmentBody, requestId: requestId(), size: 1 }, 422);
  await download(employee, attachment.url);
  await download(null, attachment.url, 401);
  await download(viewer, attachment.url, 404);
  await download(hradmin, attachment.url, 404);
  await download(other, attachment.url, 404);
  const source: any = await Attachment.findById(attachment._id).lean();
  const bytes: any = await File.findById(source.privateFile).select("+bytes").lean();
  assert.equal(bytes.storageProvider, r2 ? "r2" : "mongodb");
  if (r2) assert.equal(bytes.bytes, undefined);
  assert.equal(JSON.stringify(uploads[0]).includes("storageKey"), false);
  const approval = new mongoose.Types.ObjectId(), leaveId = new mongoose.Types.ObjectId();
  await Approval.collection.insertOne({ _id: approval, company, steps: [{ order: 1, approvers: [{ user: viewer }] }] });
  const snapshot = { attachment: new mongoose.Types.ObjectId(attachment._id), name: attachment.name, url: attachment.url, type: attachment.type, size: attachment.size };
  await Leave.collection.insertOne({ _id: leaveId, company, employee, departmentNameSnapshot: "Engineering", teamNameSnapshot: "Python", officeLocation: location, reportingManager: admin, approver: admin, approvalInstance: approval, currentApprovers: [viewer], attachments: [snapshot], status: "submitted" });
  await Attachment.collection.updateOne({ _id: source._id }, { $set: { linkedRequest: leaveId } });
  await download(viewer, attachment.url);
  await download(hr, attachment.url);
  await download(hradmin, attachment.url);
  await User.collection.updateOne({ _id: hr }, { $set: { "hrScope.departments": ["Sales"] } });
  await download(hr, attachment.url, 403);
  await User.collection.updateOne({ _id: hr }, { $set: { "hrScope.departments": ["Engineering"] } });
  await Leave.collection.updateOne({ _id: leaveId }, { $set: { attachments: [] } });
  await download(employee, attachment.url, 404);
  const correctionId = new mongoose.Types.ObjectId();
  await Correction.collection.insertOne({ _id: correctionId, company, employee, departmentNameSnapshot: "Engineering", teamNameSnapshot: "Python", officeLocation: location, reportingManager: admin, approvalInstance: approval, attachments: [snapshot], status: "submitted" });
  await Attachment.collection.updateOne({ _id: source._id }, { $set: { linkedRequest: correctionId } });
  await download(viewer, attachment.url);
  await Approval.collection.updateOne({ _id: approval }, { $set: { steps: [] } });
  await download(viewer, attachment.url, 403);
  const docRoute = `/user/updateDocuments/${employee}`;
  await call(viewer, docRoute, "GET", undefined, 403);
  await call(other, docRoute, "GET", undefined, 403);
  const legacy = { title: "Existing certificate", file: { name: "old.pdf", url: "https://example.test/old.pdf", type: "application/pdf" } };
  await Document.collection.insertOne({ user: employee, documents: [legacy], createdAt: new Date() });
  assert.equal((await call(employee, docRoute)).data.revision, 0);
  const newRow = { title: "Identity proof", isAdd: true, file: { filename: "identity.pdf", type: "application/pdf", file: data } };
  const body = { revision: 0, requestId: requestId(), documents: [legacy, newRow] };
  let result = await call(employee, docRoute, "PUT", body);
  assert.equal(result.data.revision, 1);
  assert.equal(result.data.documents[0].file.url, legacy.file.url);
  const fileUrl = result.data.documents[1].file.url;
  await download(employee, fileUrl);
  await download(hradmin, fileUrl);
  await download(hr, fileUrl);
  await download(viewer, fileUrl, 403);
  await download(other, fileUrl, 403);
  assert.equal((await call(employee, docRoute, "PUT", body)).replayed, true);
  await call(employee, docRoute, "PUT", { ...body, documents: [] }, 409);
  const count = await File.countDocuments({ company });
  await call(employee, docRoute, "PUT", { ...body, requestId: requestId() }, 409);
  assert.equal(await File.countDocuments({ company }), count, "Stale edits must fail before uploading bytes");
  await call(employee, docRoute, "PUT", { revision: 1, requestId: requestId(), documents: [{ title: "Stolen link", file: { url: attachment.url } }] }, 422);
  await call(viewer, docRoute, "PUT", { revision: 1, requestId: requestId(), documents: [] }, 403);
  await call(employee, docRoute, "PUT", { revision: 1, requestId: requestId(), documents: [{ ...newRow, file: { ...newRow.file, file: Buffer.from("Not a document").toString("base64") } }] }, 422);
  if (r2) {
    await rules({ PUT: "after_store_503", DELETE: "503" });
    const attachmentCount = await Attachment.countDocuments({ company });
    await call(employee, "/leave/attachments", "POST", { ...attachmentBody, requestId: requestId() }, 503);
    assert.equal(await Attachment.countDocuments({ company }), attachmentCount);
    await call(employee, docRoute, "PUT", { revision: 1, requestId: requestId(), documents: [newRow] }, 503);
    assert.equal((await call(employee, docRoute)).data.revision, 1);
    const pending: any = await File.findOne({ company, employee, purpose: "employee_document", storageStatus: "cleanup_pending" }).lean();
    assert.ok(pending);
    await assert.rejects(cleanupPrivateStoredFile(pending._id));
    await rules({});
    await cleanupPrivateStoredFile(pending._id);
    await download(employee, fileUrl);
    for (const mode of ["503", "corrupt"]) { await rules({ GET: mode }); await download(employee, fileUrl, 503); await download(employee, attachment.url, 503); }
    await rules({});
    const provider = process.env.HRMS_DOCUMENT_STORAGE;
    process.env.HRMS_DOCUMENT_STORAGE = "mongodb";
    await download(employee, fileUrl);
    process.env.HRMS_DOCUMENT_STORAGE = provider;
  }
  const update = { revision: 1, documents: result.data.documents };
  const simultaneous = await Promise.all([0, 1].map(async (index) => {
    const response = await fetch(`${base}/api${docRoute}`, { method: "PUT", headers: { Authorization: `Bearer ${token(employee)}`, "Content-Type": "application/json" }, body: JSON.stringify({ ...update, requestId: requestId(), documents: update.documents.map((row: any) => ({ ...row, title: `${row.title} ${index}` })) }) });
    return response.status;
  }));
  assert.deepEqual(simultaneous.sort(), [200, 409]);
  result = await call(employee, docRoute);
  await call(employee, docRoute, "PUT", { revision: result.data.revision, requestId: requestId(), documents: [] });
  await download(employee, fileUrl, 404);
  const removed: any = await File.findOne({ company, employee, purpose: "employee_document", storageStatus: "attached" }).lean();
  await cleanupPrivateStoredFile(removed._id);
  assert.equal((await File.findById(removed._id).lean() as any).storageStatus, "attached", "Removed linked evidence is retained, not orphan-deleted");
  await assert.rejects(Audit.deleteMany({ company }));
  for (const pending of await File.find({ company, storageStatus: "cleanup_pending" }).lean() as any[]) await cleanupPrivateStoredFile(pending._id);
  await Approval.collection.deleteOne({ _id: approval, company });
  await Leave.collection.deleteOne({ _id: leaveId, company });
  await Correction.collection.deleteOne({ _id: correctionId, company });
  console.log("Private storage flow API tests passed: leave/regularization participant access, legacy employee files, scoped document updates/downloads, exact/concurrent retries, stale edits, atomic failure handling and evidence retention.");
}
