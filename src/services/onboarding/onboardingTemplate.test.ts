import assert from "node:assert/strict";
import mongoose from "mongoose";
import Template from "../../schemas/Onboarding/OnboardingTemplate.schema";
import Version from "../../schemas/Onboarding/OnboardingTemplateVersion.schema";
import Audit from "../../schemas/Onboarding/OnboardingTemplateAudit.schema";
import { assertPublishable, normalizeTemplate, pagination, searchRegex } from "./onboardingTemplate.utils";
import { templateContext } from "./onboardingTemplate.service";
import { computeEffectivePermissions, getDefaultPermissionsForRole, PERMISSION_KEYS, validateUserPermissionOverrides } from "../permissions/permission.utils";

const id = () => new mongoose.Types.ObjectId().toString();
const task = { title: "Upload identity proof", instructions: "Upload a readable copy", owner: "employee", dueDays: -3, required: true, requiresDocument: true };
const input = { name: " Engineering joiner ", description: "Joining checklist", tasks: [task] };
const normalized = normalizeTemplate(input);
assert.equal(normalized.name, "Engineering joiner");
assert.equal(normalized.nameKey, "engineering joiner");
assert.equal(normalized.tasks[0].dueDays, -3);
assert.equal(normalized.tasks[0].ownerUser, null);
assert.equal(normalizeTemplate({ ...input, tasks: [] }).tasks.length, 0, "Incomplete drafts may have no tasks");
for (const invalid of [null, {}, { ...input, name: "a" }, { ...input, tasks: Array(101).fill(task) }, { ...input, tasks: [{ ...task, dueDays: 1.5 }] }, { ...input, tasks: [{ ...task, dueDays: -91 }] }, { ...input, tasks: [{ ...task, dueDays: 366 }] }, { ...input, tasks: [{ ...task, required: "false" }] }, { ...input, tasks: [{ ...task, requiresDocument: 1 }] }, { ...input, tasks: [{ ...task, owner: "manager" }] }, { ...input, tasks: [{ ...task, ownerUser: id() }] }, { ...input, tasks: [{ ...task, owner: "specific_user" }] }]) {
  assert.throws(() => normalizeTemplate(invalid));
}
const saved = normalized.tasks[0];
const existing = { ...task, _id: saved._id.toString() };
assert.equal(String(normalizeTemplate({ ...input, tasks: [existing] }, [saved]).tasks[0]._id), String(saved._id));
assert.throws(() => normalizeTemplate({ ...input, tasks: [existing] }));
assert.throws(() => normalizeTemplate({ ...input, tasks: [existing, existing] }, [saved]));
assert.throws(() => assertPublishable({ tasks: [], hasDraft: true }));
assert.throws(() => assertPublishable({ tasks: [task], hasDraft: false }));
assert.doesNotThrow(() => assertPublishable({ tasks: [task], hasDraft: true }));
assert.equal(searchRegex("[test].*")!.test("[test].*"), true);
assert.equal(searchRegex("[test].*")!.test("testing"), false);
assert.deepEqual(pagination({}), { page: 1, limit: 20, skip: 0 });
for (const invalid of [{ page: 0 }, { page: -1 }, { limit: 51 }, { page: 1.1 }, { limit: {} }]) assert.throws(() => pagination(invalid));
for (const role of ["admin", "hradmin"]) assert.equal(getDefaultPermissionsForRole(role)[PERMISSION_KEYS.MANAGE_ONBOARDING_TEMPLATES], true);
for (const role of ["hr", "user", "departmenthead", "payrollexecutive"]) assert.equal(getDefaultPermissionsForRole(role)[PERMISSION_KEYS.VIEW_ONBOARDING_TEMPLATES], false);
assert.equal(computeEffectivePermissions({ role: "hr", userOverrides: { view_onboarding_templates: true, manage_onboarding_templates: true } }).manage_onboarding_templates, true);
assert.equal(computeEffectivePermissions({ role: "hradmin", userOverrides: { view_onboarding_templates: false } }).manage_onboarding_templates, false);
assert.equal(validateUserPermissionOverrides({ role: "user", permissions: { view_onboarding_templates: true, manage_onboarding_templates: true } }).valid, true);
const company = id(), actor = { _id: id(), role: "hradmin", company };
assert.equal(String(templateContext({ user: actor }).company), company);
assert.throws(() => templateContext({ user: actor, query: { companyId: id() } }));
assert.throws(() => templateContext({ user: { ...actor, role: "user" } }));
assert.throws(() => templateContext({ user: { ...actor, role: "superadmin" } }));
assert.throws(() => templateContext({ user: { ...actor, permissions: { manage_onboarding_templates: false } } }, true));
const template = new Template({ ...normalized, company, createdBy: actor._id, updatedBy: actor._id });
assert.equal(template.validateSync(), undefined);
const version = new Version({ company, template: id(), version: 1, content: normalized, publishedBy: actor._id, reason: "First published version" });
assert.equal(version.validateSync(), undefined);
assert.ok(Template.schema.indexes().some(([fields, options]: any) => fields.company && fields.nameKey && options.unique));
assert.ok(Version.schema.indexes().some(([fields, options]: any) => fields.company && fields.template && fields.version && options.unique));
assert.ok(Audit.schema.indexes().some(([fields, options]: any) => fields.company && fields.actor && fields.requestId && options.unique));
console.log("Onboarding template unit tests passed: content, ownership, due dates, stable task IDs, publication, pagination, permissions, tenant context and schema indexes.");
