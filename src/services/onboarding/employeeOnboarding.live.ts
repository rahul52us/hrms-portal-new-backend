import assert from "node:assert/strict";
import mongoose from "mongoose";
import Instance from "../../schemas/Onboarding/EmployeeOnboarding.schema";
import Audit from "../../schemas/Onboarding/EmployeeOnboardingAudit.schema";
import Document from "../../schemas/Onboarding/OnboardingDocument.schema";
import Version from "../../schemas/Onboarding/OnboardingTemplateVersion.schema";
import User from "../../schemas/User/User";
import Notification from "../../schemas/Notification/notification.schema";
import { abandonOnboardingDocument, stageOnboardingDocument } from "./onboardingDocumentStorage";

export async function testEmployeeOnboarding(input: { company: mongoose.Types.ObjectId; hradmin: mongoose.Types.ObjectId; admin: mongoose.Types.ObjectId; hr: mongoose.Types.ObjectId; employee: mongoose.Types.ObjectId; other: mongoose.Types.ObjectId; viewer: mongoose.Types.ObjectId; disabled: mongoose.Types.ObjectId; base: string; token: (who: mongoose.Types.ObjectId) => string; call: (who: mongoose.Types.ObjectId | null, path: string, method?: string, body?: any, expected?: number) => Promise<any> }) {
  const { company, hradmin, admin, hr, employee, other, viewer, disabled, base, token, call } = input;
  await Promise.all([Instance.init(), Audit.init(), Document.init()]);
  const location = new mongoose.Types.ObjectId();
  await User.collection.updateOne({ _id: employee }, { $set: { department: "Engineering", team: "Python", officeLocation: location, joiningDate: new Date("2026-11-04"), reportingManager: admin } });
  await User.collection.updateOne({ _id: viewer }, { $set: { department: "Sales", joiningDate: new Date("2026-11-04") } });
  await User.collection.updateOne({ _id: hr }, { $set: { hrScope: { departments: ["Engineering"], teams: ["Python"], officeLocations: [location] } } });
  let sequence = 0;
  const requestId = () => `employee-onboarding-test-${++sequence}`;
  const task = (title: string, owner = "employee", extra: any = {}) => ({ title, instructions: `Complete ${title}`, owner, dueDays: 0, required: true, requiresDocument: false, ...extra });
  const content = { name: "Employee Joining Checklist", tasks: [task("Joining form"), task("Identity document", "employee", { requiresDocument: true }), task("Manager welcome", "reporting_manager"), task("HR verification", "hr"), task("IT provisioning", "specific_user", { ownerUser: String(viewer), required: false })] };
  const template = (await call(hradmin, "/templates", "POST", { ...content, requestId: requestId() }, 201)).data;
  await call(hradmin, `/templates/${template._id}/publish`, "POST", { revision: template.revision, reason: "Publish joining workflow", requestId: requestId() });
  const version: any = await Version.findOne({ company, template: template._id, version: 1 }).lean();
  assert.equal((await call(employee, "/workspace")).data.canManage, false);
  assert.equal((await call(hr, "/employees")).data.length, 1);
  assert.equal((await call(hr, `/employees?employeeId=${viewer}`)).data.length, 0);
  await call(employee, "/employees", "GET", undefined, 403);
  await call(hr, "/instances", "POST", { employeeId: viewer, templateVersionId: version._id, timezone: "Asia/Kolkata", reason: "Outside scope", requestId: requestId() }, 403);
  await call(hradmin, "/instances", "POST", { employeeId: disabled, templateVersionId: version._id, timezone: "Asia/Kolkata", reason: "Inactive employee", requestId: requestId() }, 422);
  const assignment = { employeeId: String(employee), templateVersionId: String(version._id), timezone: "Asia/Kolkata", reason: "Start employee onboarding", requestId: requestId() };
  let sheet = (await call(hradmin, "/instances", "POST", assignment, 201)).data;
  const id = sheet._id;
  assert.equal(sheet.tasks.length, 5); assert.equal(sheet.tasks[0].dueDate, "2026-11-04");
  assert.ok(sheet.tasks[3].assignees.some((person: any) => person.user === String(hr)));
  assert.equal((await call(hradmin, "/instances", "POST", assignment, 201)).replayed, true);
  assert.equal(await Instance.countDocuments({ company, employee }), 1);
  await call(hradmin, "/instances", "POST", { ...assignment, requestId: requestId() }, 409);
  await call(other, `/instances/${id}`, "GET", undefined, 404);
  await call(employee, "/instances?scope=organization", "GET", undefined, 403);
  assert.equal((await call(employee, "/instances?scope=mine")).pagination.total, 1);
  assert.equal((await call(admin, "/instances?scope=tasks")).pagination.total, 1);
  const employeeView = (await call(employee, `/instances/${id}`)).data;
  assert.equal(employeeView.tasks.length, 2, "Employee sees their own task detail, not private HR/IT tasks");
  assert.equal((await call(viewer, `/instances/${id}`)).data.tasks.length, 1);
  const act = async (who: mongoose.Types.ObjectId, action: string, taskIndex: number | null, extra: any = {}, expected = 200) => {
    const body = { action, revision: sheet.revision, reason: `QA ${action} evidence`, requestId: requestId(), ...extra };
    const response = await call(who, `/instances/${id}${taskIndex === null ? "" : `/tasks/${sheet.tasks[taskIndex]._id}`}/actions`, "POST", body, expected);
    if (expected === 200) sheet = (await call(hradmin, `/instances/${id}`)).data;
    return { response, body };
  };
  await act(employee, "complete", 2, {}, 404);
  await act(hradmin, "complete", 0, {}, 403);
  await act(employee, "complete", 1, {}, 422);
  const complete = await act(employee, "complete", 0);
  const completionAudit: any = await Audit.findOne({ company, requestId: complete.body.requestId }).lean();
  assert.equal(completionAudit.before.tasks[0].status, "pending"); assert.equal(completionAudit.after.tasks[0].status, "completed");
  await call(employee, `/instances/${id}/tasks/${sheet.tasks[0]._id}/actions`, "POST", { ...complete.body, revision: complete.body.revision }, 200);
  await act(employee, "waive", 0, {}, 403);
  const pdf = Buffer.from("%PDF-1.4\nOnboarding test document\n%%EOF");
  const r2 = process.argv.includes("--r2");
  const storageRules = async (rules: any) => {
    const response = await fetch(`${process.env.R2_TEST_ENDPOINT}/__control`, { method: "POST", body: JSON.stringify(rules) });
    assert.equal(response.status, 200);
  };
  const upload = async (who: mongoose.Types.ObjectId, bytes: Buffer, type: string, taskId = sheet.tasks[1]._id, expected = 201, key = requestId(), revision = sheet.revision) => {
    const form = new FormData(); form.set("revision", String(revision)); form.set("requestId", key); form.set("file", new Blob([new Uint8Array(bytes)], { type }), "identity.pdf");
    const response = await fetch(`${base}/api/onboarding/instances/${id}/tasks/${taskId}/documents`, { method: "POST", headers: { Authorization: `Bearer ${token(who)}` }, body: form });
    const result = await response.json() as any; assert.equal(response.status, expected, JSON.stringify(result));
    if (expected === 201) sheet = (await call(hradmin, `/instances/${id}`)).data;
    return result;
  };
  await upload(employee, Buffer.from("Not a PDF"), "application/pdf", undefined, 422);
  await upload(viewer, pdf, "application/pdf", undefined, 404);
  await upload(employee, Buffer.alloc(5 * 1024 * 1024 + 1, 32), "application/pdf", undefined, 413);
  if (r2) {
    const before = sheet.revision, secret = process.env.R2_SECRET_ACCESS_KEY;
    delete process.env.R2_SECRET_ACCESS_KEY;
    await upload(employee, pdf, "application/pdf", undefined, 503);
    process.env.R2_SECRET_ACCESS_KEY = secret;
    await storageRules({ PUT: "after_store_503", DELETE: "503" });
    await upload(employee, pdf, "application/pdf", undefined, 503);
    const failed: any = await Document.findOne({ company, storageStatus: "cleanup_pending" }).lean();
    assert.ok(failed, "Ambiguous PUT and failed cleanup must leave a recoverable private journal");
    assert.equal((await call(hradmin, `/instances/${id}`)).data.revision, before);
    assert.equal(await Audit.countDocuments({ company, action: "document_uploaded" }), 0);
    await assert.rejects(abandonOnboardingDocument(failed._id));
    assert.equal((await Document.findById(failed._id).lean() as any).storageStatus, "cleanup_pending");
    await storageRules({});
    await abandonOnboardingDocument(failed._id);
    assert.equal((await Document.findById(failed._id).lean() as any).storageStatus, "deleted");
  }
  const uploadRevision = sheet.revision, uploadKey = requestId();
  const uploaded = r2 ? (await Promise.all([0, 1].map(() => upload(employee, pdf, "application/pdf", undefined, 201, uploadKey, uploadRevision))))[0] : await upload(employee, pdf, "application/pdf", undefined, 201, uploadKey, uploadRevision);
  assert.equal((await upload(employee, pdf, "application/pdf", undefined, 201, uploadKey, uploadRevision)).replayed, true);
  assert.equal(sheet.tasks[1].documents.length, 1);
  for (let index = 0; index < 4; index++) await upload(employee, pdf, "application/pdf");
  await upload(employee, pdf, "application/pdf", undefined, 409);
  for (const extra of sheet.tasks[1].documents.slice(1)) await act(employee, "remove_document", 1, { documentId: extra.document });
  const documentId = uploaded.data.tasks.find((item: any) => item.requiresDocument).documents[0].document;
  const documentUrl = `${base}/api/onboarding/instances/${id}/tasks/${sheet.tasks[1]._id}/documents/${documentId}`;
  if (r2) {
    const metadata: any = await Document.findById(documentId).select("+bytes").lean();
    assert.equal(metadata.storageProvider, "r2"); assert.equal(metadata.bytes, undefined); assert.equal(metadata.storageStatus, "attached");
    assert.equal(metadata.storageKey.includes("identity"), false);
    await abandonOnboardingDocument(documentId);
    assert.equal((await Document.findById(documentId).lean() as any).storageStatus, "attached", "Cleanup cannot claim committed evidence");
    for (const mode of ["503", "corrupt"]) {
      await storageRules({ GET: mode });
      const response = await fetch(documentUrl, { headers: { Authorization: `Bearer ${token(employee)}` } });
      assert.equal(response.status, 503); assert.equal(response.headers.get("content-disposition"), null);
    }
    await storageRules({});
    const originalProvider = process.env.HRMS_DOCUMENT_STORAGE;
    process.env.HRMS_DOCUMENT_STORAGE = "mongodb";
    const response = await fetch(documentUrl, { headers: { Authorization: `Bearer ${token(employee)}` } });
    assert.equal(response.status, 200); assert.deepEqual(Buffer.from(await response.arrayBuffer()), pdf);
    process.env.HRMS_DOCUMENT_STORAGE = "mongodb";
    await upload(employee, pdf, "application/pdf");
    const legacyId = sheet.tasks[1].documents[sheet.tasks[1].documents.length - 1].document;
    await Document.collection.updateOne({ _id: new mongoose.Types.ObjectId(legacyId) }, { $unset: { storageProvider: "", storageStatus: "" } });
    process.env.HRMS_DOCUMENT_STORAGE = originalProvider;
    const legacy = await fetch(`${base}/api/onboarding/instances/${id}/tasks/${sheet.tasks[1]._id}/documents/${legacyId}`, { headers: { Authorization: `Bearer ${token(employee)}` } });
    assert.equal(legacy.status, 200); assert.deepEqual(Buffer.from(await legacy.arrayBuffer()), pdf);
    await act(employee, "remove_document", 1, { documentId: legacyId });
    const staged = await stageOnboardingDocument({ company, onboarding: id, task: sheet.tasks[1]._id, uploadedBy: employee, name: "crash-test.pdf", type: "application/pdf", bytes: pdf });
    await abandonOnboardingDocument(staged._id);
    assert.equal((await Document.findById(staged._id).lean() as any).storageStatus, "deleted");
    const pending: any[] = await Document.find({ company, storageStatus: "cleanup_pending" }).lean();
    for (const candidate of pending) await abandonOnboardingDocument(candidate._id);
  }
  const download = await fetch(documentUrl, { headers: { Authorization: `Bearer ${token(employee)}` } });
  assert.equal(download.status, 200); assert.equal(download.headers.get("cache-control"), "private, no-store"); assert.deepEqual(Buffer.from(await download.arrayBuffer()), pdf);
  assert.equal((await fetch(documentUrl)).status, 401);
  assert.equal((await fetch(documentUrl, { headers: { Authorization: `Bearer ${token(viewer)}` } })).status, 404);
  await act(employee, "remove_document", 1, { documentId });
  assert.equal((await fetch(documentUrl, { headers: { Authorization: `Bearer ${token(employee)}` } })).status, 404);
  await upload(employee, pdf, "application/pdf");
  await act(employee, "complete", 1);
  assert.equal(sheet.tasks[1].status, "pending_review");
  await act(hradmin, "return", 1);
  assert.equal(sheet.tasks[1].status, "pending");
  await act(employee, "complete", 1);
  await act(hradmin, "approve", 1);
  assert.equal(sheet.tasks[1].status, "completed");
  await act(admin, "complete", 2);
  await User.collection.updateOne({ _id: employee }, { $set: { department: "Sales" } });
  await call(hr, `/instances/${id}`, "GET", undefined, 404);
  assert.equal((await call(hr, "/instances?scope=tasks")).pagination.total, 0, "Former HR queue ownership cannot bypass current scope");
  await User.collection.updateOne({ _id: employee }, { $set: { department: "Engineering" } });
  await act(hr, "complete", 3);
  assert.equal(sheet.status, "completed", "Optional IT work does not block required onboarding completion");
  await act(hradmin, "reopen", 0);
  assert.equal(sheet.status, "active");
  await act(hradmin, "waive", 0);
  assert.equal(sheet.status, "completed");
  await act(hradmin, "reopen", 1);
  await act(hradmin, "reassign", 1, { assigneeIds: [String(hradmin)] });
  await upload(hradmin, pdf, "application/pdf");
  await act(hradmin, "complete", 1);
  await act(hradmin, "approve", 1, {}, 403);
  await act(admin, "approve", 1);
  const originalTasks = sheet.tasks.map((item: any) => ({ title: item.title, dueDate: item.dueDate }));
  await User.collection.updateOne({ _id: employee }, { $set: { joiningDate: new Date("2026-11-10") } });
  assert.equal((await call(hradmin, `/instances/${id}`)).data.joiningDateChanged, true);
  await act(hradmin, "reschedule", null, { timezone: "Asia/Kolkata" });
  assert.equal(sheet.tasks[0].dueDate, originalTasks[0].dueDate); assert.equal(sheet.tasks[4].dueDate, "2026-11-10");
  await act(hradmin, "reassign", 4, { assigneeIds: [String(employee)] });
  assert.equal((await call(viewer, "/instances?scope=tasks")).pagination.total, 0);
  await call(viewer, `/instances/${id}`, "GET", undefined, 404);
  const updatedTemplate = (await call(hradmin, `/templates/${template._id}`, "PUT", { name: "Employee Joining Checklist", tasks: content.tasks.map((item) => ({ ...item, title: `${item.title} changed` })), revision: 2, reason: "New intake version", requestId: requestId() })).data;
  await call(hradmin, `/templates/${template._id}/publish`, "POST", { revision: updatedTemplate.revision, reason: "Publish version two", requestId: requestId() });
  assert.equal((await call(hradmin, `/instances/${id}`)).data.tasks[0].title, "Joining form");
  await call(hradmin, "/instances", "POST", { ...assignment, requestId: requestId() }, 409);
  await User.collection.updateOne({ _id: employee }, { $unset: { reportingManager: "" } });
  const blockedTemplate = (await call(hradmin, "/templates", "POST", { name: "Blocked manager checklist", tasks: [task("Manager ownership", "reporting_manager")], requestId: requestId() }, 201)).data;
  await call(hradmin, `/templates/${blockedTemplate._id}/publish`, "POST", { revision: 1, reason: "Manager test", requestId: requestId() });
  const blockedVersion: any = await Version.findOne({ template: blockedTemplate._id }).lean();
  const blocked = (await call(hradmin, "/instances", "POST", { ...assignment, templateVersionId: String(blockedVersion._id), requestId: requestId() }, 201)).data;
  assert.equal(blocked.tasks[0].status, "blocked");
  await User.collection.updateOne({ _id: employee }, { $set: { reportingManager: admin } });
  const reassign = { action: "reassign", revision: blocked.revision, assigneeIds: [String(admin)], reason: "Assign active manager", requestId: requestId() };
  const responses = await Promise.all([reassign, { ...reassign, requestId: requestId() }].map(async (body) => (await fetch(`${base}/api/onboarding/instances/${blocked._id}/tasks/${blocked.tasks[0]._id}/actions`, { method: "POST", headers: { "Content-Type": "application/json", Authorization: `Bearer ${token(hradmin)}` }, body: JSON.stringify(body) })).status));
  assert.deepEqual(responses.sort(), [200, 409]);
  await act(hradmin, "cancel", null);
  await act(employee, "complete", 4, {}, 409);
  assert.ok(await Notification.countDocuments({ company, eventType: "onboarding.assigned" }));
  await assert.rejects(Audit.deleteMany({ company }));
  const uiTemplate = (await call(hradmin, "/templates", "POST", { name: "UI Joining Checklist", tasks: [task("Read welcome guide"), task("Upload joining document", "employee", { requiresDocument: true }), task("Manager introduction", "reporting_manager")], requestId: requestId() }, 201)).data;
  await call(hradmin, `/templates/${uiTemplate._id}/publish`, "POST", { revision: 1, reason: "Browser test checklist", requestId: requestId() });
  console.log("Employee onboarding live passed: version pinning, scoped assignments, owner visibility and blocked routing, secure document upload/download/review, completion/waiver/reopen, date updates, reassignment/revocation, cancellation, retries/concurrent writes, audit and notifications.");
  return { employeeId: String(employee), managerId: String(admin), uiTemplateId: uiTemplate._id };
}
